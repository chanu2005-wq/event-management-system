package com.eventmanagement.entity;

import com.eventmanagement.entity.enums.BookingStatus;
import jakarta.persistence.*;
import jakarta.validation.constraints.Min;
import jakarta.validation.constraints.NotNull;
import lombok.*;
import org.springframework.data.annotation.CreatedDate;
import org.springframework.data.annotation.LastModifiedDate;
import org.springframework.data.jpa.domain.support.AuditingEntityListener;

import java.math.BigDecimal;
import java.time.LocalDateTime;

/**
 * JPA entity representing a ticket booking / registration for an event.
 *
 * <p>Mapped to the {@code bookings} table in PostgreSQL.
 *
 * <p>Key business rules enforced at the service layer:
 * <ul>
 *   <li>A user cannot book the same event twice (unique constraint on user+event).</li>
 *   <li>Booking is only allowed if {@code event.availableSeats >= numberOfTickets}.</li>
 *   <li>Cancellation is only allowed while status = CONFIRMED or PENDING.</li>
 *   <li>{@code amountPaid} is a snapshot of the price at booking time (prices may change).</li>
 * </ul>
 *
 * <p>Mongoose equivalent: Booking model with user, event, numberOfTickets, status fields.
 */
@Entity
@Table(
    name = "bookings",
    uniqueConstraints = {
        // Prevents a user from booking the same event more than once
        @UniqueConstraint(
            name = "uk_bookings_user_event",
            columnNames = {"user_id", "event_id"}
        )
    },
    indexes = {
        @Index(name = "idx_bookings_user_id",   columnList = "user_id"),
        @Index(name = "idx_bookings_event_id",  columnList = "event_id"),
        @Index(name = "idx_bookings_status",    columnList = "status")
    }
)
@EntityListeners(AuditingEntityListener.class)
@Getter
@Setter
@NoArgsConstructor
@AllArgsConstructor
@Builder
public class Booking {

    // ── Primary Key ────────────────────────────────────────────────────────
    @Id
    @GeneratedValue(strategy = GenerationType.SEQUENCE, generator = "booking_seq")
    @SequenceGenerator(name = "booking_seq", sequenceName = "booking_id_seq", allocationSize = 1)
    private Long id;

    // ── Relationships ──────────────────────────────────────────────────────

    /**
     * The attendee who made this booking.
     */
    @NotNull
    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "user_id", nullable = false,
                foreignKey = @ForeignKey(name = "fk_bookings_user"))
    private User user;

    /**
     * The event being booked.
     */
    @NotNull
    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "event_id", nullable = false,
                foreignKey = @ForeignKey(name = "fk_bookings_event"))
    private Event event;

    // ── Booking Details ────────────────────────────────────────────────────

    /**
     * Number of tickets purchased in this booking.
     * Minimum is 1; the service enforces the max (based on availableSeats).
     */
    @NotNull(message = "Number of tickets is required")
    @Min(value = 1, message = "Must book at least 1 ticket")
    @Column(name = "number_of_tickets", nullable = false)
    private Integer numberOfTickets;

    /**
     * Price snapshot at the time of booking.
     * Stored so that historical bookings show the correct price even if the
     * event's price is later changed.
     */
    @Column(name = "amount_paid", nullable = false, precision = 10, scale = 2)
    private BigDecimal amountPaid;

    /**
     * Booking lifecycle status.
     * Defaults to CONFIRMED on creation (for free events / direct booking flow).
     * Can be PENDING if a payment step is introduced later.
     */
    @NotNull
    @Enumerated(EnumType.STRING)
    @Column(name = "status", nullable = false, length = 20)
    @Builder.Default
    private BookingStatus status = BookingStatus.CONFIRMED;

    /**
     * Unique booking reference shown to the user (e.g., "EMS-20240115-00042").
     * Generated by the service layer before saving.
     */
    @Column(name = "booking_reference", unique = true, length = 30)
    private String bookingReference;

    /** Optional notes or special requirements from the attendee. */
    @Column(name = "notes", columnDefinition = "TEXT")
    private String notes;

    /** Timestamp when the booking was cancelled (null if not cancelled). */
    @Column(name = "cancelled_at")
    private LocalDateTime cancelledAt;

    /** Reason for cancellation (null if not cancelled). */
    @Column(name = "cancellation_reason", length = 500)
    private String cancellationReason;

    // ── Timestamps ─────────────────────────────────────────────────────────

    @CreatedDate
    @Column(name = "created_at", nullable = false, updatable = false)
    private LocalDateTime createdAt;

    @LastModifiedDate
    @Column(name = "updated_at")
    private LocalDateTime updatedAt;

    // ── Utility ───────────────────────────────────────────────────────────

    /** Returns true if this booking can still be cancelled. */
    public boolean isCancellable() {
        return status == BookingStatus.CONFIRMED || status == BookingStatus.PENDING;
    }

    /** Returns the total cost of this booking. */
    public BigDecimal getTotalAmount() {
        return amountPaid.multiply(BigDecimal.valueOf(numberOfTickets));
    }
}
